package ArraywithNew;

class StringArray
{
    public static void main(String[] args)
    {
        String[] mobile = new String[5];

        mobile[0] = "iPhone";
        mobile[1] = "Samsung";
        mobile[2] = "OnePlus";
        mobile[3] = "Vivo";
        mobile[4] = "Oppo";

        System.out.println(mobile[0]);
        System.out.println(mobile[1]);
        System.out.println(mobile[2]);
        System.out.println(mobile[3]);
        System.out.println(mobile[4]);
    }
}